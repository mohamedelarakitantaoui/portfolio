"""Subset the self-hosted fonts (v5: Jost for display + UI, Cormorant Garamond Italic for the accent clause of a heading,
JetBrains Mono for the terminal only) to the characters the site actually uses.

Re-run after copy changes:  python scripts/subset-fonts.py   (needs: pip install fonttools brotli)
Reads every text file in src/, keeps ASCII + every non-ASCII character found, narrows the weight axis to the
weights the site uses (Jost 200-500, 500 only for <strong>; Cormorant pinned to a static 400), and writes src/assets/fonts/*.woff2 plus src/styles/fonts.css. Characters outside the
subset still render: the fontsource latin-ext files stay declared as on-demand fallbacks, and anything
else falls back to the next font in the stack.
"""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'src'
OUT = SRC / 'assets' / 'fonts'
OUT.mkdir(parents=True, exist_ok=True)
NM = ROOT / 'node_modules' / '@fontsource-variable'

chars = {chr(c) for c in range(0x20, 0x7F)}
for p in SRC.rglob('*'):
    if p.suffix in {'.ts', '.astro', '.mdx', '.md', '.json'} and 'assets' not in p.parts:
        chars |= set(p.read_text(encoding='utf-8'))
chars |= set('’‘“”«»–—…·•→←↗↘↓   ')
text = ''.join(sorted(c for c in chars if c.isprintable() or c in '  '))

FONTS = [
    # family, style, source file (latin subset), weight axis kept (range or one static weight), css weight, output name
    ('Jost Variable', 'normal', NM / 'jost/files/jost-latin-wght-normal.woff2', (200, 500), '200 500', 'jost-wght-subset.woff2'),
    ('Cormorant Garamond Variable', 'italic', NM / 'cormorant-garamond/files/cormorant-garamond-latin-wght-italic.woff2', 400, '400', 'cormorant-italic-400-subset.woff2'),
    ('JetBrains Mono Variable', 'normal', NM / 'jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2', None, '100 800', 'jetbrains-mono-wght-subset.woff2'),
]
EXT = {
    'Jost Variable': NM / 'jost/files/jost-latin-ext-wght-normal.woff2',
    'Cormorant Garamond Variable': NM / 'cormorant-garamond/files/cormorant-garamond-latin-ext-wght-italic.woff2',
    'JetBrains Mono Variable': NM / 'jetbrains-mono/files/jetbrains-mono-latin-ext-wght-normal.woff2',
}
LATIN_RANGE = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'
EXT_RANGE = 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF'

css = ['/* Generated by scripts/subset-fonts.py: do not edit by hand. */']
for family, style, src, axis, weights, name in FONTS:
    font = TTFont(src)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(text=text)
    sub.subset(font)
    if axis is not None:  # after subsetting: instancing first leaves gvar without entries for unvaried glyphs
        font = instancer.instantiateVariableFont(font, {'wght': axis})
    font.flavor = 'woff2'
    font.save(OUT / name)
    before, after = src.stat().st_size, (OUT / name).stat().st_size
    print(f'{name}: {before // 1024} KB -> {after // 1024} KB')
    rel_ext = Path('../../node_modules/@fontsource-variable') / EXT[family].relative_to(NM)
    fmt = 'woff2' if isinstance(axis, int) else 'woff2-variations'
    css.append(f"""@font-face {{
  font-family: '{family}';
  font-style: {style};
  font-display: swap;
  font-weight: {weights};
  src: url('{rel_ext.as_posix()}') format('woff2-variations');
  unicode-range: {EXT_RANGE};
}}
@font-face {{
  font-family: '{family}';
  font-style: {style};
  font-display: swap;
  font-weight: {weights};
  src: url('../assets/fonts/{name}') format('{fmt}');
  unicode-range: {LATIN_RANGE};
}}""")
(SRC / 'styles' / 'fonts.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
print(f'{len(text)} characters kept')
